`timescale 1ns/1ps
//=============================================================================
//  rgb2gray.v  —— 彩色图像转灰度（赛题【基础要求】第 2 条）
//
//      Y = (77*R + 150*G + 29*B) >> 8
//
//  系数是 0.299 / 0.587 / 0.114 的 8bit 定点近似，且 77+150+29 = 256，
//  右移 8 位即天然归一化 —— 全程没有除法器，也没有乘法器。
//
//  全部用「移位 + 加法」展开（对应赛题「用 DSP 或移位加法实现乘法」）：
//      77  = 64 + 8 + 4 + 1      -> (r<<6) + (r<<3) + (r<<2) + r
//      150 = 128 + 16 + 4 + 2    -> (g<<7) + (g<<4) + (g<<2) + (g<<1)
//      29  = 16 + 8 + 4 + 1      -> (b<<4) + (b<<3) + (b<<2) + b
//
//  位宽核算：最大值 = 256 * 255 = 65280 < 65536 -> 16bit 累加不溢出（用 17bit 更稳）
//
//  输入格式说明：
//    - RGB888（后级已扩展好）直接接
//    - RGB565 需在外部先做低位补零扩展：
//          R8 = {R5, R5[4:2]}   或   {R5, 3'b000}
//          G8 = {G6, G6[5:4]}   或   {G6, 2'b00}
//          B8 = {B5, B5[4:2]}   或   {B5, 3'b000}
//    - 若摄像头为 YUV422，Y 通道本身就是灰度，可旁路本模块（但不满足赛题的
//      「彩色转灰度」演示要求）；若为黑白 RAW，同理。
//=============================================================================
module rgb2gray (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        in_valid,   // 像素有效，接 de / href
    input  wire [7:0]  r,
    input  wire [7:0]  g,
    input  wire [7:0]  b,
    output reg         out_valid,
    output reg  [7:0]  y
);

    wire [15:0] r16 = {8'd0, r};
    wire [15:0] g16 = {8'd0, g};
    wire [15:0] b16 = {8'd0, b};

    wire [15:0] r77  = (r16 << 6) + (r16 << 3) + (r16 << 2) + r16;         // 64+8+4+1  = 77
    wire [15:0] g150 = (g16 << 7) + (g16 << 4) + (g16 << 2) + (g16 << 1);  // 128+16+4+2 = 150
    wire [15:0] b29  = (b16 << 4) + (b16 << 3) + (b16 << 2) + b16;         // 16+8+4+1  = 29

    wire [16:0] sum  = {1'b0, r77} + {1'b0, g150} + {1'b0, b29};

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            out_valid <= 1'b0;
            y         <= 8'd0;
        end else begin
            out_valid <= in_valid;
            y         <= sum[15:8];      // >> 8
        end
    end

endmodule
